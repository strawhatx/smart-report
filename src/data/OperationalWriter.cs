using Npgsql;
using NpgsqlTypes;
using SmartReport.Data.Entities;

namespace SmartReport.Data;

/// <summary>
/// Writes orders, line items, shipments and returns with <c>COPY</c>.
///
/// <para>
/// Trailhead has twenty-two months of real orders because every figure in the report is computed
/// from them — the 8,412 and the 97.2% are aggregations over rows, not constants in a view model.
/// At that volume EF's change tracker takes minutes; binary COPY takes seconds.
/// </para>
/// <para>
/// Ids are assigned here rather than by the database. These tables are never written by the
/// application — it holds SELECT only — so an identity column would be ceremony.
/// </para>
/// </summary>
internal sealed class OperationalWriter(NpgsqlConnection connection, Random random)
{
    private long _orderId = 1;
    private long _itemId = 1;
    private long _shipmentId = 1;
    private long _returnId = 1;

    /// <summary>Lateness is not spread evenly — UPS Ground accounts for about half of it.</summary>
    private static readonly (string Carrier, double Share)[] LatePropensity =
    [
        ("UPS Ground", 0.474), ("FedEx Home", 0.258), ("USPS Ground Adv.", 0.165),
        ("DHL eCommerce", 0.068), ("OnTrac", 0.035),
    ];

    public async Task WriteClientAsync(
        int clientId,
        int[] volume2025,
        int[] volume2026,
        long[] productIds,
        bool isHeadline,
        CancellationToken cancellationToken)
    {
        var orders = new List<OrderRow>();
        var items = new List<ItemRow>();
        var shipments = new List<ShipmentRow>();
        var returns = new List<ReturnRow>();

        for (var year = 2025; year <= 2026; year++)
        {
            var table = year == 2025 ? volume2025 : volume2026;

            for (var monthIndex = 0; monthIndex < table.Length; monthIndex++)
            {
                var month = new DateOnly(year, monthIndex + 1, 1);
                WriteMonth(clientId, month, table[monthIndex], productIds, isHeadline,
                    orders, items, shipments, returns);
            }
        }

        await CopyOrdersAsync(orders, cancellationToken);
        await CopyItemsAsync(items, cancellationToken);
        await CopyShipmentsAsync(shipments, cancellationToken);
        await CopyReturnsAsync(returns, cancellationToken);
    }

    private void WriteMonth(
        int clientId, DateOnly month, int count, long[] productIds, bool isHeadline,
        List<OrderRow> orders, List<ItemRow> items, List<ShipmentRow> shipments, List<ReturnRow> returns)
    {
        var daysInMonth = DateTime.DaysInMonth(month.Year, month.Month);
        var isOctober2026 = month is { Year: 2026, Month: 10 };

        // The headline month's late counts are fixed so the report reads as designed; every other
        // month ramps along a plausible improvement curve.
        var lateQuota = isHeadline && isOctober2026
            ? SeedPlan.OctoberLate.ToDictionary(x => x.Carrier, x => x.Late, StringComparer.Ordinal)
            : BuildLateQuota(count, OnTimeRateFor(month));

        // Generated by *ship* date, not order date. The metric and the trend chart both measure
        // "orders shipped in month X", so anchoring to the ship date is what makes the monthly
        // totals exact — anchoring to the order date leaks a few orders across each boundary.
        for (var i = 0; i < count; i++)
        {
            var shippedAtSlot = new DateTime(month.Year, month.Month, 1 + random.Next(daysInMonth),
                7 + random.Next(11), random.Next(60), 0, DateTimeKind.Utc);

            var channel = Pick(SeedPlan.ChannelMix, x => x.Share).Channel;
            var (carrier, service, _, billed) = Pick(SeedPlan.CarrierMix, x => x.Share);

            var runsLate = lateQuota.TryGetValue(carrier, out var remaining) && remaining > 0;
            if (runsLate)
            {
                lateQuota[carrier] = remaining - 1;
            }

            // Clamped below the promise: scaling an on-time delay past it would create a late
            // shipment outside the quota, and the on-time rate would quietly drift off target.
            var delayDays = runsLate
                ? SeedPlan.PromiseDays + 0.2 + random.NextDouble() * 3.3
                : Math.Min(
                    Pick(SeedPlan.OnTimeDelay, x => x.Weight).Days * DelayScaleFor(month),
                    SeedPlan.PromiseDays - 0.05);

            var shippedAt = shippedAtSlot;
            var orderedAt = shippedAt.AddDays(-delayDays);
            var promisedAt = orderedAt.AddDays(SeedPlan.PromiseDays);

            var orderId = _orderId++;
            orders.Add(new OrderRow(orderId, clientId, channel, orderedAt, promisedAt, shippedAt, "shipped"));

            var lines = 1 + random.Next(3);
            for (var line = 0; line < lines; line++)
            {
                items.Add(new ItemRow(_itemId++, clientId, orderId,
                    productIds[random.Next(productIds.Length)], 1 + random.Next(4)));
            }

            // is_late is derived from the two timestamps, never asserted independently — so the
            // on-time rate and the ship-time average cannot disagree with each other.
            shipments.Add(new ShipmentRow(_shipmentId++, clientId, orderId, carrier, service,
                shippedAt, shippedAt.AddDays(2 + random.NextDouble() * 4),
                shippedAt > promisedAt, billed));

            if (random.NextDouble() < SeedPlan.ReturnRate)
            {
                returns.Add(new ReturnRow(_returnId++, clientId, orderId,
                    Pick(SeedPlan.ReturnReasons, x => x.Weight).Reason,
                    shippedAt.AddDays(4 + random.NextDouble() * 20),
                    Math.Round((decimal)(12 + random.NextDouble() * 60), 2)));
            }
        }

        // The volume table counts orders that *shipped*. The most recent few days also hold
        // orders still being picked, which belong in `orders` but not in `shipments` — otherwise
        // the headline figure would quietly be "orders placed" and disagree with the carrier
        // breakdown beneath it.
        if (!isOctober2026)
        {
            return;
        }

        var stillOpen = (int)Math.Round(count * 0.011);
        for (var i = 0; i < stillOpen; i++)
        {
            var orderedAt = new DateTime(month.Year, month.Month, daysInMonth - random.Next(2),
                9 + random.Next(9), random.Next(60), 0, DateTimeKind.Utc);

            var orderId = _orderId++;
            orders.Add(new OrderRow(orderId, clientId,
                Pick(SeedPlan.ChannelMix, x => x.Share).Channel,
                orderedAt, orderedAt.AddDays(SeedPlan.PromiseDays), null, "processing"));

            items.Add(new ItemRow(_itemId++, clientId, orderId,
                productIds[random.Next(productIds.Length)], 1 + random.Next(4)));
        }
    }

    /// <summary>
    /// On-time performance improving from 94.5% in January 2025 to about 96.4% by September 2026.
    /// October is not on this curve — its late counts are fixed, which is what produces the
    /// "+0.8 pts vs September" the report shows.
    /// </summary>
    private static double OnTimeRateFor(DateOnly month)
    {
        var elapsed = (month.Year - 2025) * 12 + (month.Month - 1);
        return Math.Min(0.966, 0.945 + elapsed * 0.00095);
    }

    /// <summary>
    /// Ship times improve gradually through the period and then step down in October, when the
    /// report says Northpoint got 0.2 days faster. Scaling the whole delay distribution keeps the
    /// average honest rather than nudging one figure.
    /// </summary>
    private static double DelayScaleFor(DateOnly month)
    {
        if (month is { Year: 2026, Month: 10 })
        {
            return 1.0;
        }

        var elapsed = (month.Year - 2025) * 12 + (month.Month - 1);
        return 1.30 - Math.Min(20, elapsed) * 0.008;
    }

    private static Dictionary<string, int> BuildLateQuota(int count, double onTimeRate)
    {
        var total = (int)Math.Round(count * (1 - onTimeRate));
        return LatePropensity.ToDictionary(
            x => x.Carrier,
            x => (int)Math.Round(total * x.Share),
            StringComparer.Ordinal);
    }

    private T Pick<T>(IReadOnlyList<T> options, Func<T, double> weight)
    {
        var roll = random.NextDouble();
        var cumulative = 0.0;

        foreach (var option in options)
        {
            cumulative += weight(option);
            if (roll <= cumulative)
            {
                return option;
            }
        }

        return options[^1];
    }

    private readonly record struct OrderRow(
        long Id, int ClientId, string Channel, DateTime OrderedAt, DateTime PromisedShipAt,
        DateTime? ShippedAt, string Status);

    private readonly record struct ItemRow(long Id, int ClientId, long OrderId, long ProductId, int Quantity);

    private readonly record struct ShipmentRow(
        long Id, int ClientId, long OrderId, string Carrier, string Service,
        DateTime ShippedAt, DateTime? DeliveredAt, bool IsLate, decimal BilledAmount);

    private readonly record struct ReturnRow(
        long Id, int ClientId, long OrderId, string Reason, DateTime ReceivedAt, decimal RefundAmount);

    private async Task CopyOrdersAsync(List<OrderRow> rows, CancellationToken cancellationToken)
    {
        await using var writer = await connection.BeginBinaryImportAsync(
            "COPY orders (id, client_id, channel, ordered_at, promised_ship_at, shipped_at, status) "
            + "FROM STDIN (FORMAT BINARY)", cancellationToken);

        foreach (var row in rows)
        {
            await writer.StartRowAsync(cancellationToken);
            await writer.WriteAsync(row.Id, NpgsqlDbType.Bigint, cancellationToken);
            await writer.WriteAsync(row.ClientId, NpgsqlDbType.Integer, cancellationToken);
            await writer.WriteAsync(row.Channel, NpgsqlDbType.Varchar, cancellationToken);
            await writer.WriteAsync(row.OrderedAt, NpgsqlDbType.TimestampTz, cancellationToken);
            await writer.WriteAsync(row.PromisedShipAt, NpgsqlDbType.TimestampTz, cancellationToken);
            if (row.ShippedAt is { } shipped)
            {
                await writer.WriteAsync(shipped, NpgsqlDbType.TimestampTz, cancellationToken);
            }
            else
            {
                await writer.WriteNullAsync(cancellationToken);
            }
            await writer.WriteAsync(row.Status, NpgsqlDbType.Varchar, cancellationToken);
        }

        await writer.CompleteAsync(cancellationToken);
    }

    private async Task CopyItemsAsync(List<ItemRow> rows, CancellationToken cancellationToken)
    {
        await using var writer = await connection.BeginBinaryImportAsync(
            "COPY order_items (id, client_id, order_id, product_id, quantity) FROM STDIN (FORMAT BINARY)",
            cancellationToken);

        foreach (var row in rows)
        {
            await writer.StartRowAsync(cancellationToken);
            await writer.WriteAsync(row.Id, NpgsqlDbType.Bigint, cancellationToken);
            await writer.WriteAsync(row.ClientId, NpgsqlDbType.Integer, cancellationToken);
            await writer.WriteAsync(row.OrderId, NpgsqlDbType.Bigint, cancellationToken);
            await writer.WriteAsync(row.ProductId, NpgsqlDbType.Bigint, cancellationToken);
            await writer.WriteAsync(row.Quantity, NpgsqlDbType.Integer, cancellationToken);
        }

        await writer.CompleteAsync(cancellationToken);
    }

    private async Task CopyShipmentsAsync(List<ShipmentRow> rows, CancellationToken cancellationToken)
    {
        await using var writer = await connection.BeginBinaryImportAsync(
            "COPY shipments (id, client_id, order_id, carrier, service, shipped_at, delivered_at, is_late, billed_amount) "
            + "FROM STDIN (FORMAT BINARY)", cancellationToken);

        foreach (var row in rows)
        {
            await writer.StartRowAsync(cancellationToken);
            await writer.WriteAsync(row.Id, NpgsqlDbType.Bigint, cancellationToken);
            await writer.WriteAsync(row.ClientId, NpgsqlDbType.Integer, cancellationToken);
            await writer.WriteAsync(row.OrderId, NpgsqlDbType.Bigint, cancellationToken);
            await writer.WriteAsync(row.Carrier, NpgsqlDbType.Varchar, cancellationToken);
            await writer.WriteAsync(row.Service, NpgsqlDbType.Varchar, cancellationToken);
            await writer.WriteAsync(row.ShippedAt, NpgsqlDbType.TimestampTz, cancellationToken);
            if (row.DeliveredAt is { } delivered)
            {
                await writer.WriteAsync(delivered, NpgsqlDbType.TimestampTz, cancellationToken);
            }
            else
            {
                await writer.WriteNullAsync(cancellationToken);
            }
            await writer.WriteAsync(row.IsLate, NpgsqlDbType.Boolean, cancellationToken);
            await writer.WriteAsync(row.BilledAmount, NpgsqlDbType.Numeric, cancellationToken);
        }

        await writer.CompleteAsync(cancellationToken);
    }

    private async Task CopyReturnsAsync(List<ReturnRow> rows, CancellationToken cancellationToken)
    {
        await using var writer = await connection.BeginBinaryImportAsync(
            "COPY returns (id, client_id, order_id, reason, received_at, refund_amount) FROM STDIN (FORMAT BINARY)",
            cancellationToken);

        foreach (var row in rows)
        {
            await writer.StartRowAsync(cancellationToken);
            await writer.WriteAsync(row.Id, NpgsqlDbType.Bigint, cancellationToken);
            await writer.WriteAsync(row.ClientId, NpgsqlDbType.Integer, cancellationToken);
            await writer.WriteAsync(row.OrderId, NpgsqlDbType.Bigint, cancellationToken);
            await writer.WriteAsync(row.Reason, NpgsqlDbType.Varchar, cancellationToken);
            await writer.WriteAsync(row.ReceivedAt, NpgsqlDbType.TimestampTz, cancellationToken);
            await writer.WriteAsync(row.RefundAmount, NpgsqlDbType.Numeric, cancellationToken);
        }

        await writer.CompleteAsync(cancellationToken);
    }
}
